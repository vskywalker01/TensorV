library IEEE;
use IEEE.STD_LOGIC_1164.ALL;
use ieee.math_real.all;
use work.REGISTERS.ALL;

package PE_MATRIX_PARAMETERS is 
    constant DEPTH: INTEGER := 8; 
    constant PROCESSING_ELEMENTS: INTEGER := DEPTH**2;
    
    constant QUEUE_SIZE: INTEGER := 8;
    constant QUEUE_COUNTERS_SIZE: INTEGER := get_register_address_size(QUEUE_SIZE);
    
    constant BUFFER_SIZE: INTEGER := 16; 
    constant BUFFER_COUNTERS_SIZE: INTEGER := get_register_address_size(BUFFER_SIZE);
    
    constant DATA_SIZE: INTEGER := 8;
    constant ACCUMULATOR_SIZE: INTEGER := (DATA_SIZE*2)+INTEGER(ceil(log2(REAL(DEPTH))));
    
    
    -- Definition of control bus
    -- This connections are use to control the PE 
    constant CONTROL_SIZE: INTEGER := (QUEUE_COUNTERS_SIZE*2)+7; 
    
    constant ACTIVATION_SKIP_MS_BIT:        INTEGER := CONTROL_SIZE-1;
    constant ACTIVATION_SKIP_LS_BIT:        INTEGER := ACTIVATION_SKIP_MS_BIT-QUEUE_COUNTERS_SIZE+1;
    constant ACCUMULATIONS_NUMBER_MS_BIT:   INTEGER := ACTIVATION_SKIP_LS_BIT-1; 
    constant ACCUMULATIONS_NUMBER_LS_BIT:   INTEGER := ACCUMULATIONS_NUMBER_MS_BIT - QUEUE_COUNTERS_SIZE+1;
    
    constant ACTIVATION_INIT_BIT:           INTEGER := ACCUMULATIONS_NUMBER_LS_BIT-1; 
    constant WEIGHT_INIT_BIT:               INTEGER := ACTIVATION_INIT_BIT-1;
    constant ACCUMULATOR_INIT_BIT:          INTEGER := WEIGHT_INIT_BIT-1;
    
    constant ACTIVATION_VALID_BIT:          INTEGER := ACCUMULATOR_INIT_BIT-1;
    constant WEIGHT_VALID_BIT:              INTEGER := ACTIVATION_VALID_BIT-1; 
 
    constant PROCESS_ENABLE_BIT:            INTEGER := WEIGHT_VALID_BIT-1; 
    constant PROCESS_TYPE_BIT:              INTEGER := PROCESS_ENABLE_BIT-1; 
    
    -- Definition of status bus
    -- These line are used to communicate the internal state of the PE 
    
    constant STATUS_SIZE:            INTEGER := 4;
    constant ACCUMULATOR_VALID_BIT:  INTEGER := STATUS_SIZE-1;
    constant ACTIVE_BIT:             INTEGER := ACCUMULATOR_VALID_BIT-1;
    constant TYPE_BIT:               INTEGER := ACTIVE_BIT-1;
    constant DONE_BIT:               INTEGER := TYPE_BIT-1;
    
    constant CONTROL_LINES:          INTEGER := DEPTH;
    constant ACTIVATION_LINES:       INTEGER := (DEPTH*2)-1; 
    constant WEIGHT_LINES:           INTEGER := (DEPTH);
    constant ACCUMULATION_LINES:     INTEGER := (DEPTH);
    constant STATUS_LINES:           INTEGER := DEPTH;
    
    -- Definition of the core's control interface 
    
    constant BUFFER_INTERFACE_SIZE:           INTEGER := 1;
    constant BUFFER_INTERFACE_ADD_BIT:        INTEGER := BUFFER_INTERFACE_SIZE-1;
    
    constant MATRIX_STATUS_SIZE:                    INTEGER := DEPTH+ACTIVATION_LINES+WEIGHT_LINES+ACCUMULATION_LINES; 
    constant MATRIX_STATUS_DONE_MSB:                INTEGER := MATRIX_STATUS_SIZE-1;
    constant MATRIX_STATUS_DONE_LSB:                INTEGER := MATRIX_STATUS_DONE_MSB-DEPTH+1; 
    constant MATRIX_STATUS_WEIGHTS_READY_MSB:       INTEGER := MATRIX_STATUS_DONE_LSB-1;
    constant MATRIX_STATUS_WEIGHTS_READY_LSB:       INTEGER := MATRIX_STATUS_WEIGHTS_READY_MSB-WEIGHT_LINES+1;
    constant MATRIX_STATUS_ACTIVATIONS_READY_MSB:   INTEGER := MATRIX_STATUS_WEIGHTS_READY_LSB-1;
    constant MATRIX_STATUS_ACTIVATIONS_READY_LSB:   INTEGER := MATRIX_STATUS_ACTIVATIONS_READY_MSB-ACTIVATION_LINES+1;
    constant MATRIX_STATUS_OUTPUTS_READY_MSB:       INTEGER := MATRIX_STATUS_ACTIVATIONS_READY_LSB-1;
    constant MATRIX_STATUS_OUTPUTS_READY_LSB:       INTEGER := MATRIX_STATUS_OUTPUTS_READY_MSB-ACCUMULATION_LINES+1;
    
    constant ROWS_ENABLE_BITS:                  INTEGER := INTEGER(ceil(log2(REAL(ACTIVATION_LINES))));
    constant COLS_ENABLE_BITS:                  INTEGER := INTEGER(ceil(log2(REAL(DEPTH))));
     
    constant MATRIX_CONTROL_INTERFACE_SIZE:                 INTEGER := ROWS_ENABLE_BITS+COLS_ENABLE_BITS+(QUEUE_COUNTERS_SIZE*5)+8;
    constant MATRIX_CONTROL_ROWS_ENABLE_MSB:                INTEGER := MATRIX_CONTROL_INTERFACE_SIZE-1; 
    constant MATRIX_CONTROL_ROWS_ENABLE_LSB:                INTEGER := MATRIX_CONTROL_ROWS_ENABLE_MSB-ROWS_ENABLE_BITS+1;
    constant MATRIX_CONTROL_COLS_ENABLE_MSB:                INTEGER := MATRIX_CONTROL_ROWS_ENABLE_LSB-1; 
    constant MATRIX_CONTROL_COLS_ENABLE_LSB:                INTEGER := MATRIX_CONTROL_COLS_ENABLE_MSB-COLS_ENABLE_BITS+1; 
    constant MATRIX_CONTROL_ACTIVATION_BUFFERS_INIT_BIT:    INTEGER := MATRIX_CONTROL_COLS_ENABLE_LSB-1; 
    constant MATRIX_CONTROL_WEIGHT_BUFFERS_INIT_BIT:        INTEGER := MATRIX_CONTROL_ACTIVATION_BUFFERS_INIT_BIT-1; 
    constant MATRIX_CONTROL_OUTPUT_BUFFERS_INIT_BIT:        INTEGER := MATRIX_CONTROL_WEIGHT_BUFFERS_INIT_BIT-1; 
    constant MATRIX_CONTROL_SEND_ACTIVATION_SIZE_MSB:       INTEGER := MATRIX_CONTROL_OUTPUT_BUFFERS_INIT_BIT-1;
    constant MATRIX_CONTROL_SEND_ACTIVATION_SIZE_LSB:       INTEGER := MATRIX_CONTROL_SEND_ACTIVATION_SIZE_MSB-QUEUE_COUNTERS_SIZE+1;
    constant MATRIX_CONTROL_SEND_WEIGHT_SIZE_MSB:           INTEGER := MATRIX_CONTROL_SEND_ACTIVATION_SIZE_LSB-1;
    constant MATRIX_CONTROL_SEND_WEIGHT_SIZE_LSB:           INTEGER := MATRIX_CONTROL_SEND_WEIGHT_SIZE_MSB-QUEUE_COUNTERS_SIZE+1;
    constant MATRIX_CONTROL_SEND_OUTPUT_SIZE_MSB:           INTEGER := MATRIX_CONTROL_SEND_WEIGHT_SIZE_LSB-1;
    constant MATRIX_CONTROL_SEND_OUTPUT_SIZE_LSB:           INTEGER := MATRIX_CONTROL_SEND_OUTPUT_SIZE_MSB-QUEUE_COUNTERS_SIZE+1;
    
    constant MATRIX_CONTROL_ROW_SKIP_MSB:                   INTEGER := MATRIX_CONTROL_SEND_OUTPUT_SIZE_LSB-1; 
    constant MATRIX_CONTROL_ROW_SKIP_LSB:                   INTEGER := MATRIX_CONTROL_ROW_SKIP_MSB-QUEUE_COUNTERS_SIZE+1;
    constant MATRIX_CONTROL_ROW_RESULTS_MSB:                INTEGER := MATRIX_CONTROL_ROW_SKIP_LSB-1; 
    constant MATRIX_CONTROL_ROW_RESULTS_LSB:                INTEGER := MATRIX_CONTROL_ROW_RESULTS_MSB-QUEUE_COUNTERS_SIZE+1;
    constant MATRIX_CONTROL_SEND_ACTIVATION_BUFFERS_BIT:    INTEGER := MATRIX_CONTROL_ROW_RESULTS_LSB-1;
    constant MATRIX_CONTROL_SEND_WEIGHT_BUFFERS_BIT:        INTEGER := MATRIX_CONTROL_SEND_ACTIVATION_BUFFERS_BIT-1;
    constant MATRIX_CONTROL_SEND_OUTPUT_BUFFERS_BIT:        INTEGER := MATRIX_CONTROL_SEND_WEIGHT_BUFFERS_BIT-1;
    constant MATRIX_CONTROL_PROCESS_ENABLE_BIT:             INTEGER := MATRIX_CONTROL_SEND_OUTPUT_BUFFERS_BIT-1; 
    constant MATRIX_CONTROL_PROCESS_TYPE_BIT:               INTEGER := MATRIX_CONTROL_PROCESS_ENABLE_BIT-1;
    
    
    
    type MATRIX_INTERCONNECT_DATA is array (DEPTH-1 downto 0, DEPTH-1 downto 0) of STD_LOGIC_VECTOR(DATA_SIZE-1 downto 0);
    type MATRIX_INTERCONNECT_ACCUMULATOR is array (DEPTH-1 downto 0, DEPTH-1 downto 0) of STD_LOGIC_VECTOR(ACCUMULATOR_SIZE-1 downto 0);
    type MATRIX_INTERCONNECT_CONTROL is array (DEPTH-1 downto 0, DEPTH-1 downto 0) of STD_LOGIC_VECTOR(CONTROL_SIZE-1 downto 0);
    type MATRIX_INTERCONNECT_STATUS is array (DEPTH-1 downto 0, DEPTH-1 downto 0) of STD_LOGIC_VECTOR(STATUS_SIZE-1 downto 0);
    
    subtype MATRIX_CONTROL_INTERFACE is STD_LOGIC_VECTOR(MATRIX_CONTROL_INTERFACE_SIZE-1 downto 0);
    subtype MATRIX_STATUS_INTERFACE is STD_LOGIC_VECTOR(MATRIX_STATUS_SIZE-1 downto 0);
    
    type MATRIX_ACTIVATIONS_DATA_INTERFACE is array (ACTIVATION_LINES-1 downto 0) of STD_LOGIC_VECTOR(DATA_SIZE-1 downto 0);
    type MATRIX_ACTIVATIONS_CONTROL_INTERFACE is array (ACTIVATION_LINES-1 downto 0) of STD_LOGIC_VECTOR(BUFFER_INTERFACE_SIZE-1 downto 0);
    
    type MATRIX_WEIGHTS_DATA_INTERFACE is array (WEIGHT_LINES-1 downto 0) of STD_LOGIC_VECTOR(DATA_SIZE-1 downto 0);
    type MATRIX_WEIGHTS_CONTROL_INTERFACE is array (WEIGHT_LINES-1 downto 0) of STD_LOGIC_VECTOR(BUFFER_INTERFACE_SIZE-1 downto 0);
    
    type MATRIX_OUTPUTS_DATA_INTERFACE is array (ACCUMULATION_LINES-1 downto 0) of STD_LOGIC_VECTOR(ACCUMULATOR_SIZE-1 downto 0);
    type MATRIX_OUTPUTS_CONTROL_INTERFACE is array (ACCUMULATION_LINES-1 downto 0) of STD_LOGIC_VECTOR(BUFFER_INTERFACE_SIZE-1 downto 0);
    
    
    
    
end package; 
