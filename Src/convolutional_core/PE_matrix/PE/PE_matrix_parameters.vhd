library IEEE;
use IEEE.STD_LOGIC_1164.ALL;
use ieee.math_real.all;
use work.REGISTERS.ALL;

package PE_MATRIX_PARAMETERS is 

    -- The depth marapeter defines the size of the convolutional matrix. The number of PEs that are used is defined by the DEPTH parameter 
    constant DEPTH: INTEGER := 8; 
    constant PROCESSING_ELEMENTS: INTEGER := DEPTH**2;
    
    -- The number of lines used for managing between PEs interconnections
    constant CONTROL_LINES:          INTEGER := DEPTH;
    constant ACTIVATION_LINES:       INTEGER := (DEPTH*2)-1; 
    constant WEIGHT_LINES:           INTEGER := (DEPTH);
    constant ACCUMULATION_LINES:     INTEGER := (DEPTH);
    constant STATUS_LINES:           INTEGER := DEPTH;
    
    -- activation's bitwidth
    constant DATA_SIZE: INTEGER := 8;
    
    -- accumulator's bitwidth (used in the internal structure of the PE)
    constant ACCUMULATOR_SIZE: INTEGER := (DATA_SIZE*2)+INTEGER(ceil(log2(REAL(DEPTH+1))));
    
    -- Bit size used to define the specific dimensions in the matrix control interface.
    constant ACTIVATION_MATRIX_SIZE_BITS:           INTEGER := INTEGER(ceil(log2(REAL(ACTIVATION_LINES))));
    constant WEIGHT_MATRIX_SIZE_BITS:               INTEGER := INTEGER(ceil(log2(REAL(DEPTH))));
    constant CONV_SHIFTS_BITS:                      INTEGER := INTEGER(ceil(log2(REAL(DEPTH))))+1;
    constant CONV_SKIP_BITS:                        INTEGER := INTEGER(ceil(log2(REAL(DEPTH))))+1;
    constant REQUANTIZATION_SHIFT_BITS:             INTEGER := INTEGER(ceil(log2(REAL(ACCUMULATOR_SIZE))));
    
    -- Dimension of the convolutional core buffers    
    constant BUFFER_SIZE: INTEGER := 16; 
    constant BUFFER_SIZE_BITS: INTEGER := INTEGER(ceil(log2(REAL(BUFFER_SIZE))));
    
    -- Definition of PE control lines (used to control a single PE)
    
    constant PE_INIT:                       INTEGER := 0;
    constant PE_ACTIVATIONS_CLEAR:          INTEGER := PE_INIT+1; 
    constant PE_WEIGHTS_CLEAR:              INTEGER := PE_ACTIVATIONS_CLEAR+1;
    constant PE_PROCESS_START:              INTEGER := PE_WEIGHTS_CLEAR+1;
    constant PE_PROCESS_TYPE:               INTEGER := PE_PROCESS_START+1;
    constant PE_WEIGHT_VALID:               INTEGER := PE_PROCESS_TYPE+1;
    constant PE_ACTIVATION_VALID:           INTEGER := PE_WEIGHT_VALID+1;
    constant PE_CONV_SHIFTS_LSB:            INTEGER := PE_ACTIVATION_VALID+1;
    constant PE_CONV_SHIFTS_MSB:            INTEGER := PE_CONV_SHIFTS_LSB+CONV_SHIFTS_BITS-1;
    constant PE_CONV_SKIP_LSB:              INTEGER := PE_CONV_SHIFTS_MSB+1;
    constant PE_CONV_SKIP_MSB:              INTEGER := PE_CONV_SKIP_LSB+CONV_SKIP_BITS-1;
    constant PE_CONTROL_INTERFACE_SIZE:     INTEGER := PE_CONV_SKIP_MSB+1; 
    
    -- Definition of PE status lines (used as status lines from a single PE)
    
    constant PE_ACTIVE:                 INTEGER := 0;
    constant PE_STATUS_TYPE:            INTEGER := PE_ACTIVE+1;
    constant PE_STATUS_WAITING:         INTEGER := PE_STATUS_TYPE+1;
    constant PE_OUTPUT_VALID:           INTEGER := PE_STATUS_WAITING+1;
    constant PE_READY:                  INTEGER := PE_OUTPUT_VALID+1;
    constant PE_STATUS_INTERFACE_SIZE:  INTEGER := PE_READY+1;
    
    -- Definition of the convolutional core buffer control lines 
      
    constant MATRIX_BUFFERS_ADD_ACTIVATIONS_LSB:    INTEGER := 0;
    constant MATRIX_BUFFERS_ADD_ACTIVATIONS_MSB:    INTEGER := MATRIX_BUFFERS_ADD_ACTIVATIONS_LSB+ACTIVATION_LINES-1;
    constant MATRIX_BUFFERS_ADD_WEIGHTS_LSB:        INTEGER := MATRIX_BUFFERS_ADD_ACTIVATIONS_MSB+1;
    constant MATRIX_BUFFERS_ADD_WEIGHTS_MSB:        INTEGER := MATRIX_BUFFERS_ADD_WEIGHTS_LSB+WEIGHT_LINES-1;
    constant MATRIX_BUFFERS_ADD_BIAS_LSB:           INTEGER := MATRIX_BUFFERS_ADD_WEIGHTS_MSB+1;
    constant MATRIX_BUFFERS_ADD_BIAS_MSB:           INTEGER := MATRIX_BUFFERS_ADD_BIAS_LSB+ACCUMULATION_LINES-1;
    constant MATRIX_BUFFERS_GET_OUTPUTS_LSB:        INTEGER := MATRIX_BUFFERS_ADD_BIAS_MSB+1; 
    constant MATRIX_BUFFERS_GET_OUTPUTS_MSB:        INTEGER := MATRIX_BUFFERS_GET_OUTPUTS_LSB+ACCUMULATION_LINES-1; 
    constant MATRIX_BUFFERS_ACTIVATIONS_INIT:       INTEGER := MATRIX_BUFFERS_GET_OUTPUTS_MSB +1;
    constant MATRIX_BUFFERS_WEIGHTS_INIT:           INTEGER := MATRIX_BUFFERS_ACTIVATIONS_INIT+1;
    constant MATRIX_BUFFERS_BIAS_INIT:              INTEGER := MATRIX_BUFFERS_WEIGHTS_INIT+1;
    constant MATRIX_BUFFERS_OUTPUTS_INIT:           INTEGER := MATRIX_BUFFERS_BIAS_INIT+1;
    constant MATRIX_BUFFERS_CONTROL_INTERFACE_SIZE: INTEGER := MATRIX_BUFFERS_OUTPUTS_INIT+1;
        
    -- Definition of convolutional core buffers status lines 

    constant MATRIX_BUFFERS_STATUS_ACTIVATIONS_READY_LSB:       INTEGER := 0;
    constant MATRIX_BUFFERS_STATUS_ACTIVATIONS_READY_MSB:       INTEGER := MATRIX_BUFFERS_STATUS_ACTIVATIONS_READY_LSB+ACTIVATION_LINES-1;
    constant MATRIX_BUFFERS_STATUS_WEIGHTS_READY_LSB:           INTEGER := MATRIX_BUFFERS_STATUS_ACTIVATIONS_READY_MSB+1;
    constant MATRIX_BUFFERS_STATUS_WEIGHTS_READY_MSB:           INTEGER := MATRIX_BUFFERS_STATUS_WEIGHTS_READY_LSB+WEIGHT_LINES-1;
    constant MATRIX_BUFFERS_STATUS_BIAS_READY_LSB:              INTEGER := MATRIX_BUFFERS_STATUS_WEIGHTS_READY_MSB+1;
    constant MATRIX_BUFFERS_STATUS_BIAS_READY_MSB:              INTEGER := MATRIX_BUFFERS_STATUS_BIAS_READY_LSB+ACCUMULATION_LINES-1;
    constant MATRIX_BUFFERS_STATUS_OUTPUT_READY_LSB:            INTEGER := MATRIX_BUFFERS_STATUS_BIAS_READY_MSB+1;
    constant MATRIX_BUFFERS_STATUS_OUTPUT_READY_MSB:            INTEGER := MATRIX_BUFFERS_STATUS_OUTPUT_READY_LSB+ACCUMULATION_LINES-1;
    constant MATRIX_BUFFERS_STATUS_OUTPUT_VALID_LSB:            INTEGER := MATRIX_BUFFERS_STATUS_OUTPUT_READY_MSB+1;
    constant MATRIX_BUFFERS_STATUS_OUTPUT_VALID_MSB:            INTEGER := MATRIX_BUFFERS_STATUS_OUTPUT_VALID_LSB+ACCUMULATION_LINES-1;
    constant MATRIX_BUFFERS_STATUS_INTERFACE_SIZE:              INTEGER := MATRIX_BUFFERS_STATUS_OUTPUT_VALID_MSB+1;
    
    -- Definition of the convolutional core control lines 
    
    constant MATRIX_COMMAND_SIZE:                           INTEGER := 2;
    constant MATRIX_COMMAND_INIT:                           STD_LOGIC_VECTOR(MATRIX_COMMAND_SIZE-1 downto 0) := "00"; 
    constant MATRIX_COMMAND_LOAD:                           STD_LOGIC_VECTOR(MATRIX_COMMAND_SIZE-1 downto 0) := "01"; 
    constant MATRIX_COMMAND_COMPUTE:                        STD_LOGIC_VECTOR(MATRIX_COMMAND_SIZE-1 downto 0) := "10"; 
    constant MATRIX_COMMAND_UNLOAD:                         STD_LOGIC_VECTOR(MATRIX_COMMAND_SIZE-1 downto 0) := "11";
            
    constant MATRIX_CONTROL_COMMAND_VALID:                  INTEGER := 0;
    constant MATRIX_CONTROL_COMMAND_TYPE_LSB:               INTEGER := MATRIX_CONTROL_COMMAND_VALID+1; 
    constant MATRIX_CONTROL_COMMAND_TYPE_MSB:               INTEGER := MATRIX_CONTROL_COMMAND_TYPE_LSB+MATRIX_COMMAND_SIZE-1;
    constant MATRIX_CONTROL_CLEAR_ACTIVATIONS_FLAG:         INTEGER := MATRIX_CONTROL_COMMAND_TYPE_MSB+1;
    constant MATRIX_CONTROL_CLEAR_WEIGHTS_FLAG:             INTEGER := MATRIX_CONTROL_CLEAR_ACTIVATIONS_FLAG+1;
    constant MATRIX_CONTROL_LOAD_WEIGHTS_FLAG:              INTEGER := MATRIX_CONTROL_CLEAR_WEIGHTS_FLAG+1;
    constant MATRIX_CONTROL_LOAD_ACTIVATIONS_FLAG:          INTEGER := MATRIX_CONTROL_LOAD_WEIGHTS_FLAG+1;
    constant MATRIX_CONTROL_LOAD_BIAS_FLAG:                 INTEGER := MATRIX_CONTROL_LOAD_ACTIVATIONS_FLAG+1;
    
    constant MATRIX_CONTROL_ACTIVATION_SIZE_X_LSB:          INTEGER := MATRIX_CONTROL_LOAD_BIAS_FLAG+1; 
    constant MATRIX_CONTROL_ACTIVATION_SIZE_X_MSB:          INTEGER := MATRIX_CONTROL_ACTIVATION_SIZE_X_LSB+ACTIVATION_MATRIX_SIZE_BITS-1;
    constant MATRIX_CONTROL_ACTIVATION_SIZE_Y_LSB:          INTEGER := MATRIX_CONTROL_ACTIVATION_SIZE_X_MSB+1;
    constant MATRIX_CONTROL_ACTIVATION_SIZE_Y_MSB:          INTEGER := MATRIX_CONTROL_ACTIVATION_SIZE_Y_LSB+ACTIVATION_MATRIX_SIZE_BITS-1; 
    constant MATRIX_CONTROL_WEIGHT_SIZE_X_LSB:              INTEGER := MATRIX_CONTROL_ACTIVATION_SIZE_Y_MSB +1;
    constant MATRIX_CONTROL_WEIGHT_SIZE_X_MSB:              INTEGER := MATRIX_CONTROL_WEIGHT_SIZE_X_LSB+WEIGHT_MATRIX_SIZE_BITS-1;
    constant MATRIX_CONTROL_WEIGHT_SIZE_Y_LSB:              INTEGER := MATRIX_CONTROL_WEIGHT_SIZE_X_MSB+1;
    constant MATRIX_CONTROL_WEIGHT_SIZE_Y_MSB:              INTEGER := MATRIX_CONTROL_WEIGHT_SIZE_Y_LSB+WEIGHT_MATRIX_SIZE_BITS-1;
    constant MATRIX_CONTROL_CONV_SHIFTS_X_LSB:              INTEGER := MATRIX_CONTROL_WEIGHT_SIZE_Y_MSB +1;
    constant MATRIX_CONTROL_CONV_SHIFTS_X_MSB:              INTEGER := MATRIX_CONTROL_CONV_SHIFTS_X_LSB+CONV_SHIFTS_BITS-1; 
    constant MATRIX_CONTROL_CONV_SHIFTS_Y_LSB:              INTEGER := MATRIX_CONTROL_CONV_SHIFTS_X_MSB+1;
    constant MATRIX_CONTROL_CONV_SHIFTS_Y_MSB:              INTEGER := MATRIX_CONTROL_CONV_SHIFTS_Y_LSB+CONV_SHIFTS_BITS-1;
    constant MATRIX_CONTROL_CONV_SKIP_X_LSB:                INTEGER := MATRIX_CONTROL_CONV_SHIFTS_Y_MSB+1;
    constant MATRIX_CONTROL_CONV_SKIP_X_MSB:                INTEGER := MATRIX_CONTROL_CONV_SKIP_X_LSB+CONV_SKIP_BITS-1;
    constant MATRIX_CONTROL_REQUANTIZATION_SHIFT_LSB:       INTEGER := MATRIX_CONTROL_CONV_SKIP_X_MSB+1;
    constant MATRIX_CONTROL_REQUANTIZATION_SHIFT_MSB:       INTEGER := MATRIX_CONTROL_REQUANTIZATION_SHIFT_LSB+REQUANTIZATION_SHIFT_BITS-1;
    
    constant MATRIX_CONTROL_INTERFACE_SIZE:                 INTEGER := MATRIX_CONTROL_REQUANTIZATION_SHIFT_MSB+1;
    
    -- Definition of the convolutional core status lines
    
    constant MATRIX_STATUS_LINES_READY_LSB:                 INTEGER := 0;
    constant MATRIX_STATUS_LINES_READY_MSB:                 INTEGER := MATRIX_STATUS_LINES_READY_LSB+DEPTH-1;
    constant MATRIX_STATUS_LINES_WAITING_LSB:               INTEGER := MATRIX_STATUS_LINES_READY_MSB+1;
    constant MATRIX_STATUS_LINES_WAITING_MSB:               INTEGER := MATRIX_STATUS_LINES_WAITING_LSB+DEPTH-1;
    constant MATRIX_STATUS_SIZE:                            INTEGER := MATRIX_STATUS_LINES_WAITING_MSB+1; 
    
    subtype PE_CONTROL_INTERFACE is STD_LOGIC_VECTOR(PE_CONTROL_INTERFACE_SIZE-1 downto 0); 
    subtype PE_STATUS_INTERFACE is STD_LOGIC_VECTOR(PE_STATUS_INTERFACE_SIZE-1 downto 0);

    subtype MATRIX_CONTROL_INTERFACE is STD_LOGIC_VECTOR(MATRIX_CONTROL_INTERFACE_SIZE-1 downto 0);
    subtype MATRIX_STATUS_INTERFACE is STD_LOGIC_VECTOR(MATRIX_STATUS_SIZE-1 downto 0);
    
    subtype MATRIX_BUFFERS_CONTROL_INTERFACE is STD_LOGIC_VECTOR(MATRIX_BUFFERS_CONTROL_INTERFACE_SIZE-1 downto 0);
    subtype MATRIX_BUFFERS_STATUS_INTERFACE is STD_LOGIC_VECTOR(MATRIX_BUFFERS_STATUS_INTERFACE_SIZE-1 downto 0);
    
    subtype MATRIX_ACTIVATIONS_DATA_INTERFACE is STD_LOGIC_VECTOR(DATA_SIZE-1 downto 0);
    subtype MATRIX_WEIGHTS_DATA_INTERFACE is STD_LOGIC_VECTOR(DATA_SIZE-1 downto 0);
    subtype MATRIX_BIAS_DATA_INTERFACE is STD_LOGIC_VECTOR(DATA_SIZE-1 downto 0);
    subtype MATRIX_OUTPUTS_DATA_INTERFACE is STD_LOGIC_VECTOR(DATA_SIZE-1 downto 0);
    
end package; 
